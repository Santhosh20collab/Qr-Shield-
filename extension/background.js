import { scanImage, singleResult } from "./api.js";

const MENU_ID = "qrshield-scan-image";
const STORAGE_KEY = "qrshieldResult";
const ERROR_KEY = "qrshieldError";

chrome.runtime.onInstalled.addListener(() => {
  chrome.contextMenus.removeAll(() => {
    chrome.contextMenus.create({
      id: MENU_ID,
      title: "Scan image with QR Shield",
      contexts: ["image"],
    });
  });
});

function filenameFrom(url) {
  try {
    const parsed = new URL(url);
    const last = parsed.pathname.split("/").filter(Boolean).pop() || "image";
    return decodeURIComponent(last).slice(0, 80);
  } catch (_) {
    return "image";
  }
}

async function fetchImage(url) {
  if (url.startsWith("blob:")) {
    throw new Error("This image is generated by the page. Save it, then scan the file from the popup.");
  }
  const response = await fetch(url, { credentials: "omit", cache: "no-store" });
  if (!response.ok) {
    throw new Error(`Could not download the image (HTTP ${response.status}).`);
  }
  const blob = await response.blob();
  if (!blob.type.startsWith("image/")) {
    throw new Error("That link is not an image.");
  }
  if (blob.size > 12 * 1024 * 1024) {
    throw new Error("Image is larger than 12 MB.");
  }
  return blob;
}

function setBadge(result) {
  let text = "";
  let color = "#0f9d68";
  if (result.verdict === "malicious") {
    text = "!";
    color = "#dc2626";
  } else if (result.verdict === "suspicious") {
    text = "?";
    color = "#b45309";
  }
  chrome.action.setBadgeText({ text });
  if (text) {
    chrome.action.setBadgeBackgroundColor({ color });
    chrome.action.setTitle({
      title: `QR Shield · risk ${Math.round(Number(result.score) || 0)}/100 · ${result.verdict}`,
    });
  }
}

async function openResultWindow() {
  await chrome.windows.create({
    url: chrome.runtime.getURL("result.html"),
    type: "popup",
    width: 448,
    height: 660,
  });
}

async function scanAndShow(srcUrl) {
  try {
    const blob = await fetchImage(srcUrl);
    const filename = filenameFrom(srcUrl);
    const data = await scanImage(blob, filename);
    const result = singleResult(data);
    await chrome.storage.session.set({
      [STORAGE_KEY]: { result, filename, at: Date.now() },
      [ERROR_KEY]: null,
    });
    setBadge(result);
  } catch (error) {
    await chrome.storage.session.set({
      [ERROR_KEY]: String((error && error.message) || error || "Scan failed."),
    });
  }
  await openResultWindow();
}

chrome.contextMenus.onClicked.addListener((info) => {
  if (info.menuItemId !== MENU_ID || !info.srcUrl) return;
  scanAndShow(info.srcUrl);
});
